/**
 * Lists evaluation scenarios filtered optionally by category.
 */
export function listKnowledgeEvalScenarios(category?: KnowledgeEvalCategory): KnowledgeEvalScenario[] {
  if (!category) return KNOWLEDGE_EVAL_DATASET;
  return KNOWLEDGE_EVAL_DATASET.filter((s) => s.category === category);
}

/**
 * Retrieves a single evaluation scenario by its unique identifier.
 */
export function getKnowledgeEvalScenario(id: string): KnowledgeEvalScenario | undefined {
  return KNOWLEDGE_EVAL_DATASET.find((s) => s.id === id);
}
