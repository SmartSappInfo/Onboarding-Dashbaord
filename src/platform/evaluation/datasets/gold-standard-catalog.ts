/**
 * Retrieves a gold-standard scenario by its unique scenario ID.
 */
export function getGoldStandardScenarioById(id: string): EvaluationScenario | undefined {
  return GOLD_STANDARD_SCENARIOS.find((s) => s.id === id);
}

/**
 * Retrieves all gold-standard scenarios belonging to a specific operational domain.
 */
export function getGoldStandardScenariosByDomain(
  domain: EvaluationDomain
): readonly EvaluationScenario[] {
  return GOLD_STANDARD_SCENARIOS.filter((s) => s.domain === domain);
}

/**
 * Returns total count of registered gold-standard scenarios.
 */
export function getGoldStandardCatalogCount(): number {
  return GOLD_STANDARD_SCENARIOS.length;
}
